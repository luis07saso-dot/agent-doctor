"""R9 daily metrics + R10 mailbox alert -> docs/metrics.md.

Reads the events file written on the VPS by deploy/collect_logs.sh (REQ lines with hashed
ids, mailbox poll errors, hourly Almanac heartbeats, process starts). Never reads message
text: there is none in the logs.

Usage (from the repo root; --pull needs SSH, so run with the sandbox off):
    .venv/bin/python scripts/metrics.py --pull     # copy events from the VPS, then report
    .venv/bin/python scripts/metrics.py            # report from data/events.log
    .venv/bin/python scripts/metrics.py --file x   # report from another copy
    .venv/bin/python scripts/metrics.py --sessions # also print guard budget per chat session
Rewrites only the block between the markers in docs/metrics.md, so re-runs never duplicate.
Exit code 2 = an outage alert in the newest day of data.

Definitions (also written into the doc):
- chat message: any Chat Protocol REQ except session markers (`input=control`).
- answered: not `dropped` by the guard. Target: >= 99% answered, p95 latency < 15 s.
- errors: api_down, timeout, fallback, prehire_error (the user got "try again").
- Pre-Hire protocol calls: `input=prehire_protocol` (other agents, not chat).
- outside use: senders in scripts/metrics_exclude.json removed. A sender hash is not a
  person: ASI:One may relay many users under one sender, so sessions are shown too.
- mailbox error streak (R10): mailbox poll errors with no quiet gap over 330 s. uagents
  0.26.1 polls every 1 s and logs only failed polls; aiohttp's default 300 s timeout bounds
  the gap between two failed polls. So a streak = the mailbox kept failing. A successful
  poll inside a streak is invisible (not logged); a streak >= 30 min raises an ALERT.
- heartbeat gap: uagents logs "Registration on Almanac API successful" every 3600 s while
  the agent runs. A gap over 90 min between heartbeats/starts raises an ALERT.
"""
from __future__ import annotations

import argparse
import json
import statistics
import subprocess
import sys
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EVENTS = ROOT / "data" / "events.log"
DOC = ROOT / "docs" / "metrics.md"
EXCLUDE = ROOT / "scripts" / "metrics_exclude.json"
VPS_HOST = "root@YOUR_VPS_IP"
VPS_EVENTS = "/opt/agent-doctor/logs/events.log"
SSH_OPTS = ["-o", "BatchMode=yes", "-o", "ConnectTimeout=15"]

START_MARK = "<!-- metrics:start (generated by scripts/metrics.py; edits inside are overwritten) -->"
END_MARK = "<!-- metrics:end -->"

ANSWERED_TARGET = 99.0
P95_TARGET_MS = 15_000
STREAK_GAP_S = 330  # 300 s aiohttp default total timeout + 1 s poll + margin
STREAK_ALERT_S = 30 * 60
HEARTBEAT_ALERT_S = 90 * 60  # heartbeat every 3600 s; one missed beat + margin
ERROR_OUTCOMES = {"api_down", "timeout", "fallback", "prehire_error"}
PROTOCOL = "prehire_protocol"
# Mirror of agent/guard.py (tests keep them equal). The guard counts only messages it let
# through, per (sender, session), in memory: a restart (START) resets it.
GUARD_HOURLY_CAP = 20
GUARD_DAILY_CAP = 50
GUARD_NOT_COUNTED = {"dropped", "rate_limited", "repeat"}  # guard said no
GUARD_SKIPPED_INPUTS = {"control", "non_text", PROTOCOL}  # never reach the guard


@dataclass(frozen=True)
class Event:
    ts: datetime
    kind: str  # REQ | MAILBOX_ERR | HEARTBEAT | START | HANDLER_ERR
    data: dict = field(default_factory=dict)


def parse_ts(s: str) -> datetime:
    """Docker RFC3339Nano UTC ('2026-11-02T10:03:12.157616347Z') -> aware datetime (µs)."""
    s = s.rstrip("Z")
    base, _, frac = s.partition(".")
    dt = datetime.strptime(base, "%Y-%m-%dT%H:%M:%S").replace(tzinfo=timezone.utc)
    return dt + timedelta(microseconds=int((frac + "000000")[:6])) if frac else dt


def parse_events(lines) -> list[Event]:
    """Bad or unknown lines are skipped, never fatal."""
    out = []
    for line in lines:
        parts = line.rstrip("\n").split(" ", 2)
        if len(parts) < 2:
            continue
        try:
            ts = parse_ts(parts[0])
        except ValueError:
            continue
        kind, rest = parts[1], parts[2] if len(parts) > 2 else ""
        if kind == "REQ":
            try:
                rec = json.loads(rest)
            except ValueError:
                continue
            if isinstance(rec, dict):
                out.append(Event(ts, "REQ", rec))
        elif kind == "MAILBOX_ERR":
            out.append(Event(ts, kind, {"status": rest.partition("status=")[2] or "?"}))
        elif kind in ("HEARTBEAT", "START", "HANDLER_ERR"):
            out.append(Event(ts, kind))
    out.sort(key=lambda e: e.ts)
    return out


def pct(values: list[int], q: float) -> int | None:
    """Nearest-rank percentile; None for no data."""
    if not values:
        return None
    v = sorted(values)
    k = max(0, min(len(v) - 1, int(-(-q * len(v) // 100)) - 1))  # ceil(q*n/100) - 1
    return v[k]


@dataclass
class Streak:
    start: datetime
    end: datetime
    errors: int
    statuses: Counter

    @property
    def seconds(self) -> float:
        return (self.end - self.start).total_seconds()


def mailbox_streaks(events: list[Event], gap_s: float = STREAK_GAP_S) -> list[Streak]:
    out: list[Streak] = []
    for e in events:
        if e.kind != "MAILBOX_ERR":
            continue
        st = e.data.get("status", "?")
        if out and (e.ts - out[-1].end).total_seconds() <= gap_s:
            out[-1].end = e.ts
            out[-1].errors += 1
            out[-1].statuses[st] += 1
        else:
            out.append(Streak(e.ts, e.ts, 1, Counter({st: 1})))
    return out


def heartbeat_gaps(events: list[Event], now: datetime | None = None) -> list[tuple[datetime, datetime]]:
    """(from, to) between consecutive heartbeats/starts, plus last beat -> `now` if given."""
    beats = [e.ts for e in events if e.kind in ("HEARTBEAT", "START")]
    gaps = list(zip(beats, beats[1:]))
    if beats and now is not None and now > beats[-1]:
        gaps.append((beats[-1], now))
    return gaps


def load_exclude(path: Path = EXCLUDE) -> dict[str, str]:
    """{sender_hash: label}. Missing file = no exclusions."""
    try:
        raw = json.loads(path.read_text())
    except (OSError, ValueError):
        return {}
    return {str(k): str(v) for k, v in (raw.get("senders") or {}).items()}


def day_stats(events: list[Event], exclude: dict[str, str]) -> dict:
    reqs = [e.data for e in events if e.kind == "REQ"]
    chat = [r for r in reqs if r.get("input") not in (PROTOCOL, "control")]
    proto = [r for r in reqs if r.get("input") == PROTOCOL]
    answered = [r for r in chat if r.get("outcome") != "dropped"]
    lat = [int(r.get("latency_ms", 0)) for r in answered]
    outcomes = Counter(str(r.get("outcome")) for r in chat)
    outside = [r for r in chat if r.get("sender") not in exclude]
    outside_proto = [r for r in proto if r.get("sender") not in exclude]
    excluded = Counter(exclude[r["sender"]] for r in chat + proto if r.get("sender") in exclude)
    return {
        "chat": len(chat),
        "answered": len(answered),
        "answered_pct": round(100 * len(answered) / len(chat), 1) if chat else None,
        "errors": sum(outcomes[o] for o in ERROR_OUTCOMES),
        "fallbacks": outcomes["fallback"],
        "prehire_pending": outcomes["prehire_pending"],
        "dropped": outcomes["dropped"],
        "p50": pct(lat, 50), "p95": pct(lat, 95), "max": max(lat) if lat else None,
        "outcomes": outcomes,
        "proto_calls": len(proto),
        "proto_outcomes": Counter(str(r.get("outcome")) for r in proto),
        "handler_errors": sum(1 for e in events if e.kind == "HANDLER_ERR"),
        "out_senders": len({r.get("sender") for r in outside}),
        "out_sessions": len({(r.get("sender"), r.get("session")) for r in outside}),
        "out_msgs": len(outside),
        "audits": sum(1 for r in outside if r.get("outcome") in ("ok", "partial")),
        "fix_guides": sum(1 for r in outside if str(r.get("outcome")).startswith("fix_guide")),
        "prehire_chat": sum(1 for r in outside if str(r.get("outcome")).startswith("prehire_")),
        "clicks": Counter(str(r["click"]) for r in chat if r.get("click")),
        "out_proto_callers": len({r.get("sender") for r in outside_proto}),
        "excluded": excluded,
        "excluded_sessions": len({(r.get("sender"), r.get("session"))
                                  for r in chat if r.get("sender") in exclude}),
        "mailbox_errors": Counter(e.data.get("status", "?") for e in events if e.kind == "MAILBOX_ERR"),
        "heartbeats": sum(1 for e in events if e.kind == "HEARTBEAT"),
    }


def by_day(events: list[Event]) -> dict[str, list[Event]]:
    days: dict[str, list[Event]] = defaultdict(list)
    for e in events:
        days[e.ts.strftime("%Y-%m-%d")].append(e)
    return dict(sorted(days.items()))


def _hm(dt: datetime) -> str:
    return dt.strftime("%Y-%m-%d %H:%M")


def _dur(s: float) -> str:
    m = int(s // 60)
    return f"{m // 60}h{m % 60:02d}m" if m >= 60 else f"{m}m"


def _n(v) -> str:
    return "–" if v is None else str(v)


def _counts(c: Counter) -> str:
    return ", ".join(f"{k} {v}" for k, v in sorted(c.items())) or "–"


def alerts(events: list[Event], now: datetime | None = None) -> list[tuple[str, str]]:
    """[(day, text)] for outages (R10) and missed reliability targets (R9)."""
    out: list[tuple[str, str]] = []
    last_ts = events[-1].ts if events else None
    for s in mailbox_streaks(events):
        if s.seconds >= STREAK_ALERT_S:
            ongoing = " (still failing at the last collected line)" if s.end == last_ts else ""
            out.append((s.end.strftime("%Y-%m-%d"),
                        f"ALERT mailbox: errors {_hm(s.start)}–{s.end.strftime('%H:%M')} UTC "
                        f"({_dur(s.seconds)}, {s.errors} errors: {_counts(s.statuses)}){ongoing}"))
    for a, b in heartbeat_gaps(events, now):
        if (b - a).total_seconds() > HEARTBEAT_ALERT_S:
            to = "now" if now is not None and b == now else f"{_hm(b)} UTC"
            out.append((b.strftime("%Y-%m-%d"),
                        f"ALERT heartbeat: none from {_hm(a)} UTC to {to} ({_dur((b - a).total_seconds())})"))
    for day, evs in by_day(events).items():
        st = day_stats(evs, {})
        if st["answered_pct"] is not None and st["answered_pct"] < ANSWERED_TARGET:
            out.append((day, f"TARGET missed: {st['answered_pct']}% answered (< {ANSWERED_TARGET:g}%)"))
        if st["p95"] is not None and st["p95"] >= P95_TARGET_MS:
            out.append((day, f"TARGET missed: p95 {st['p95']} ms (>= {P95_TARGET_MS} ms)"))
    return sorted(out)


def render(events: list[Event], exclude: dict[str, str], now: datetime | None = None) -> str:
    days = {d: (day_stats(evs, exclude), evs) for d, evs in by_day(events).items()}
    streaks = mailbox_streaks(events)
    gaps = heartbeat_gaps(events, now)
    lines = []
    if events:
        lines.append(f"Data: {_hm(events[0].ts)} – {_hm(events[-1].ts)} UTC, {len(events)} events. "
                     f"Generated {_hm(now or datetime.now(timezone.utc))} UTC.")
    else:
        lines.append("Data: no events yet.")
    lines += ["", "### Reliability (all traffic, R9)", "",
              "| day (UTC) | chat msgs | answered | answered % | errors | fallbacks | pre-hire pending "
              "| dropped | p50 ms | p95 ms | max ms | Pre-Hire protocol calls | handler errors |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for d, (s, _) in days.items():
        lines.append(f"| {d} | {s['chat']} | {s['answered']} | {_n(s['answered_pct'])} | {s['errors']} "
                     f"| {s['fallbacks']} | {s['prehire_pending']} | {s['dropped']} | {_n(s['p50'])} "
                     f"| {_n(s['p95'])} | {_n(s['max'])} | {s['proto_calls']} | {s['handler_errors']} |")
    lines += ["", "### Use (exclusions removed, R9)", "",
              "| day (UTC) | outside chat senders | outside chat sessions | outside chat msgs | audits "
              "| fix guides | pre-hire (chat) | card clicks | outside Pre-Hire callers (agents) "
              "| excluded msgs | excluded sessions |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
    for d, (s, _) in days.items():
        lines.append(f"| {d} | {s['out_senders']} | {s['out_sessions']} | {s['out_msgs']} | {s['audits']} "
                     f"| {s['fix_guides']} | {s['prehire_chat']} | {_counts(s['clicks'])} "
                     f"| {s['out_proto_callers']} | {_counts(s['excluded'])} | {s['excluded_sessions']} |")
    lines += ["", "### Mailbox and heartbeat (R10)", "",
              "| day (UTC) | mailbox errors | by status | error streaks | longest streak "
              "| heartbeats | longest heartbeat gap |",
              "|---|---|---|---|---|---|---|"]
    for d, (s, evs) in days.items():
        ds = [x for x in streaks if x.end.strftime("%Y-%m-%d") == d]
        dg = [(b - a).total_seconds() for a, b in gaps if b.strftime("%Y-%m-%d") == d]
        lines.append(f"| {d} | {sum(s['mailbox_errors'].values())} | {_counts(s['mailbox_errors'])} "
                     f"| {len(ds)} | {_dur(max(x.seconds for x in ds)) if ds else '–'} "
                     f"| {s['heartbeats']} | {_dur(max(dg)) if dg else '–'} |")
    lines += ["", "### Outcomes per day (chat)", ""]
    for d, (s, _) in days.items():
        proto = f" · protocol: {_counts(s['proto_outcomes'])}" if s["proto_calls"] else ""
        lines.append(f"- {d}: {_counts(s['outcomes'])}{proto}")
    al = alerts(events, now)
    lines += ["", "### Alerts", ""]
    lines += [f"- {d}: {t}" for d, t in al] or ["- none"]
    return "\n".join(lines)


def update_doc(doc: Path, block: str) -> None:
    """Replace the generated block; keep everything outside the markers."""
    text = doc.read_text() if doc.exists() else f"# Metrics\n\n{START_MARK}\n{END_MARK}\n"
    if START_MARK not in text or END_MARK not in text:
        text = text.rstrip("\n") + f"\n\n{START_MARK}\n{END_MARK}\n"
    head, rest = text.split(START_MARK, 1)
    _, tail = rest.split(END_MARK, 1)
    doc.write_text(f"{head}{START_MARK}\n{block}\n{END_MARK}{tail}")


def pull(dest: Path = EVENTS) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_suffix(".tmp")
    with tmp.open("wb") as f:
        r = subprocess.run(["ssh", *SSH_OPTS, VPS_HOST, f"cat {VPS_EVENTS}"], stdout=f,
                           stderr=subprocess.PIPE, timeout=60)
    if r.returncode != 0:
        tmp.unlink(missing_ok=True)
        raise SystemExit(f"pull failed (ssh exit {r.returncode}): "
                         f"{r.stderr.decode(errors='replace').strip()[:200]}")
    tmp.replace(dest)


def guard_budget(events: list[Event], now: datetime | None = None) -> list[dict]:
    """Per chat session since the last restart: replies the guard counted in the last hour /
    24 h and what is left before it silences the session for 24 h. Use before each Testing
    batch. Log time ~ reply time (the guard counts at receipt, up to 15 s earlier).
    Over-counts blank-text messages (logged like a normal help reply, not guard-checked)."""
    if not events:
        return []
    now = now or events[-1].ts
    starts = [e.ts for e in events if e.kind == "START"]
    since = max(starts) if starts else events[0].ts
    hour, day = now - timedelta(hours=1), now - timedelta(days=1)
    sessions: dict[tuple, dict] = {}
    for e in events:
        if e.kind != "REQ" or e.ts < since or e.data.get("input") in GUARD_SKIPPED_INPUTS:
            continue
        key = (e.data.get("sender", "?"), e.data.get("session", "?"))
        s = sessions.setdefault(key, {"sender": key[0], "session": key[1], "times": [],
                                      "held": Counter(), "first": e.ts, "last": e.ts})
        s["last"] = e.ts
        out = e.data.get("outcome")
        if out in GUARD_NOT_COUNTED:
            s["held"][out] += 1
        else:
            s["times"].append(e.ts)
    rows = []
    for s in sessions.values():
        times = s.pop("times")
        in_day = [t for t in times if t > day]
        # Busiest rolling hour in the last 2 days: once it hit the cap, the next message
        # trips a 24 h silence (or already did).
        recent = [t for t in times if t > now - timedelta(days=2)]
        peak = max((sum(1 for u in recent if t <= u < t + timedelta(hours=1)) for t in recent),
                   default=0)
        tripped = peak >= GUARD_HOURLY_CAP or len(in_day) >= GUARD_DAILY_CAP
        s.update(hour=sum(1 for t in times if t > hour), day=len(in_day), tripped=tripped,
                 held=dict(s["held"]))
        s["hour_left"] = 0 if tripped else GUARD_HOURLY_CAP - s["hour"]
        s["day_left"] = 0 if tripped else GUARD_DAILY_CAP - s["day"]
        rows.append(s)
    rows.sort(key=lambda r: r["last"], reverse=True)
    return rows


def render_budget(rows: list[dict], exclude: dict[str, str]) -> str:
    if not rows:
        return "Guard budget: no chat sessions since the last restart."
    out = ["Guard budget since last restart (caps: %d/h, %d/24 h per session; at cap = silent 24 h)"
           % (GUARD_HOURLY_CAP, GUARD_DAILY_CAP),
           "sender       session  last (UTC)        1h  24h  left/h  left/24h  held  who"]
    for r in rows:
        held = ",".join(f"{k}={v}" for k, v in sorted(r["held"].items())) or "-"
        flag = "  TRIPPED/AT CAP" if r["tripped"] else ""
        out.append(f"{r['sender']:<12} {r['session']:<8} {r['last']:%Y-%m-%d %H:%M}  "
                   f"{r['hour']:>3} {r['day']:>4}  {r['hour_left']:>6}  {r['day_left']:>8}  "
                   f"{held}  {exclude.get(r['sender'], '?')}{flag}")
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--pull", action="store_true", help="copy the events file from the VPS first")
    ap.add_argument("--file", type=Path, default=EVENTS)
    ap.add_argument("--doc", type=Path, default=DOC)
    ap.add_argument("--exclude", type=Path, default=EXCLUDE)
    ap.add_argument("--sessions", action="store_true",
                    help="also print the guard budget per chat session (before Testing runs)")
    a = ap.parse_args(argv)
    if a.pull:
        pull(a.file)
    if not a.file.exists():
        print(f"No events file at {a.file}. Run with --pull (sandbox off).", file=sys.stderr)
        return 1
    events = parse_events(a.file.read_text(errors="replace").splitlines())
    # "No heartbeat since X until now" only makes sense for freshly pulled data.
    now = datetime.now(timezone.utc) if a.pull else None
    update_doc(a.doc, render(events, load_exclude(a.exclude), now))
    al = alerts(events, now)
    newest = by_day(events) and list(by_day(events))[-1]
    for d, t in al:
        print(f"{d}: {t}")
    print(f"{len(events)} events -> {a.doc}")
    if a.sessions:
        print(render_budget(guard_budget(events, now), load_exclude(a.exclude)))
    return 2 if any(d == newest and t.startswith("ALERT") for d, t in al) else 0


if __name__ == "__main__":
    sys.exit(main())
