// Agent Doctor eval scorer. Deterministic: same reply in, same number out.
// Task score = 0.5 * diagnosis + 0.5 * rewrite, each 0..1. Run score = 100 * mean task score.
//   diagnosis = max(0, caught - 0.5 * noise) / |expected|   (|expected| = 0: 1 if no noise, else 0)
//     caught = distinct expected rule ids reported; noise = unknown, unexpected or duplicate rule ids
//   rewrite = mean of 6 checks (Doctor rubric text checks + keyword + owner-term checks)
// passed = diagnosis == 1 and rewrite == 1.
import { readdirSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const NOISE_PENALTY = 0.5;
export const RULES = ["active", "chat_protocol", "readme_sections", "readme", "rating", "description", "responsive",
  "handle", "avatar", "interactions", "success_rate", "eval_rate", "website", "starter_prompts"] as const;
// Doctor rubric constants (agent/rubric.py, SCORING_VERSION 2).
const README_MIN_CHARS = 300, README_SHORT = 3 / 8, DESC_MIN_CHARS = 40, DESC_SHORT = 2 / 6, SUMMARY_INTRO_MIN = 80;
export const KEYWORDS_MAX = 10; // project rule (CLAUDE.md), not an Agentverse doc limit
const SECTIONS: Record<string, string[]> = {
  "Summary": ["summary", "overview", "about", "introduction", "description", "what it does", "what this agent does", "what the agent does"],
  "Key features": ["feature", "capabilit", "what you can ask", "what it can do", "what the agent can do"],
  "Usage": ["usage", "how to use", "getting started", "quick start", "quickstart", "example input", "example output", "example quer",
    "example request", "example prompt", "how to call", "commands", "input and output", "inputs"],
  "Use cases": ["use case", "use-case", "usecase", "scenario", "who is it for", "who it's for", "applications"],
  "Limitations": ["limitation", "known issue", "caveat", "cannot do", "can't do", "not supported", "disclaimer", "constraints"],
  "Metadata": ["metadata", "credit", "author", "version", "license", "licence", "contact", "changelog", "maintainer"],
};

/** Profile snapshot in a task file (spec §4.4). Every key is always present. */
export interface Profile { name: string; handle: string; description: string; readme: string; avatar: boolean; chat_protocol: boolean;
  status: "active" | "inactive"; unresponsive: boolean; rating: number | null; total_interactions: number | null;
  recent_success_rate: number | null; recent_verified_interactions: number; recent_eval_success_rate: number | null;
  domain: string | null; starter_prompts: string[] }
/** Task file evals/tasks/NN-slug.json (spec §4.4). "expected" is generated by evals/gen_expected.py, never hand-written. */
export interface Task { id: string; title: string; holdout: boolean; profile: Profile; job: string; must_keep: string[]; expected: { rule: string; why: string }[] }
export interface Rewrite { description: string; readme: string; keywords: string[]; starter_prompts: string[] }
export interface Check { name: string; score: number; detail: string }
export interface TaskScore { task_id: string; holdout: boolean; score: number; passed: boolean; parsed: boolean;
  diagnosis: number; rewrite: number; caught: string[]; missed: { rule: string; why: string }[]; noise: string[]; checks: Check[] }

const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const round = (x: number, d: number) => Math.round(x * 10 ** d) / 10 ** d;
const str = (v: unknown) => (typeof v === "string" ? v : "");
const strs = (v: unknown) => (Array.isArray(v) ? v.filter((x) => typeof x === "string" && x.trim()).map((x) => x.trim()) : []);

/** Port of agent/scorer.py readme_sections_found. */
export function readmeSections(readme: string): string[] {
  const headings: string[] = [];
  let intro = 0, seen = false, fence = false;
  for (const line of readme.split(/\r?\n/)) {
    if (/^\s*(```|~~~)/.test(line)) { fence = !fence; continue; }
    if (fence) continue;
    const m = line.match(/^\s{0,3}#{1,6}\s+(.+?)\s*#*\s*$/);
    if (m) { headings.push(m[1].toLowerCase()); if (headings.length > 1) seen = true; }
    else if (!seen) intro += line.trim().length;
  }
  return Object.entries(SECTIONS).filter(([sec, ps]) =>
    headings.some((h) => ps.some((p) => new RegExp("(?<![a-z0-9])" + esc(p)).test(h))) || (sec === "Summary" && intro >= SUMMARY_INTRO_MIN),
  ).map(([sec]) => sec);
}

/** The last ```json block (or the whole reply if bare JSON) with "findings" (array) and "rewrite" (object). */
export function parseReply(reply: string): { findings: string[]; rewrite: Rewrite } | null {
  const blocks = [...reply.matchAll(/```json\s*\n([\s\S]*?)```/g)].map((m) => m[1]);
  try {
    const o = JSON.parse((blocks.length ? blocks[blocks.length - 1] : reply).trim());
    if (!o || !Array.isArray(o.findings) || !o.rewrite || typeof o.rewrite !== "object") return null;
    const findings = o.findings.map((f: any) => String(f?.rule ?? "").trim().toLowerCase());
    const r = o.rewrite;
    return { findings, rewrite: { description: str(r.description), readme: str(r.readme), keywords: strs(r.keywords), starter_prompts: strs(r.starter_prompts) } };
  } catch { return null; }
}

export function rewriteChecks(task: Task, r: Rewrite): Check[] {
  const found = readmeSections(r.readme);
  const missing = Object.keys(SECTIONS).filter((s) => !found.includes(s));
  const n = r.readme.trim().length, d = r.description.trim().length;
  const hay = (r.readme + "\n" + r.description).toLowerCase();
  const kwIn = r.keywords.filter((k) => hay.includes(k.toLowerCase()));
  const kwOut = r.keywords.filter((k) => !kwIn.includes(k));
  const keep = task.must_keep.filter((k) => r.readme.toLowerCase().includes(k.toLowerCase()));
  const kwScore = r.keywords.length === 0 || r.keywords.length > KEYWORDS_MAX ? 0 : kwIn.length / r.keywords.length;
  return [
    { name: "readme_sections", score: found.length / 6, detail: missing.length ? `README missing sections: ${missing.join(", ")}` : "6/6 sections" },
    { name: "readme_length", score: n === 0 ? 0 : n < README_MIN_CHARS ? README_SHORT : 1, detail: `README ${n} chars (min ${README_MIN_CHARS})` },
    { name: "description", score: d === 0 ? 0 : d < DESC_MIN_CHARS ? DESC_SHORT : 1, detail: `description ${d} chars (min ${DESC_MIN_CHARS})` },
    { name: "keywords", score: kwScore, detail: r.keywords.length === 0 ? "no keywords" : r.keywords.length > KEYWORDS_MAX
      ? `${r.keywords.length} keywords (max ${KEYWORDS_MAX})` : kwOut.length ? `keywords not in README or description: ${kwOut.join(", ")}` : "all keywords appear" },
    { name: "owner_terms", score: task.must_keep.length ? keep.length / task.must_keep.length : 1,
      detail: keep.length === task.must_keep.length ? "README keeps the owner's terms" : "README drops terms from the owner's note" },
    { name: "starter_prompts", score: r.starter_prompts.length ? 1 : 0, detail: `${r.starter_prompts.length} starter prompts` },
  ];
}

export function scoreTask(task: Task, reply: string): TaskScore {
  const base = { task_id: task.id, holdout: !!task.holdout };
  const p = parseReply(reply);
  if (!p) return { ...base, score: 0, passed: false, parsed: false, diagnosis: 0, rewrite: 0, caught: [], missed: [...task.expected], noise: [], checks: [] };
  const want = new Set(task.expected.map((e) => e.rule));
  const caught: string[] = [], noise: string[] = [];
  for (const rule of p.findings) (want.has(rule) && !caught.includes(rule) ? caught : noise).push(rule);
  const diagnosis = want.size ? Math.max(0, caught.length - NOISE_PENALTY * noise.length) / want.size : noise.length ? 0 : 1;
  const checks = rewriteChecks(task, p.rewrite);
  const rewrite = checks.reduce((s, c) => s + c.score, 0) / checks.length;
  return { ...base, score: round(0.5 * diagnosis + 0.5 * rewrite, 4), passed: diagnosis === 1 && rewrite === 1, parsed: true,
    diagnosis: round(diagnosis, 4), rewrite: round(rewrite, 4), caught, missed: task.expected.filter((e) => !caught.includes(e.rule)), noise, checks };
}

export function scoreRun(ts: TaskScore[]) {
  const mean = ts.length ? ts.reduce((s, t) => s + t.score, 0) / ts.length : 0;
  return { score: round(100 * mean, 2), tasks_passed: ts.filter((t) => t.passed).length, tasks_total: ts.length };
}

// ---------- CLI: npm run score -- --selftest | <dir with results.json> ----------
const here = dirname(fileURLToPath(import.meta.url));
const tasksDir = process.env.TASKS_DIR ?? join(here, "tasks");
const load = (): Task[] => readdirSync(tasksDir).filter((f) => f.endsWith(".json")).sort().map((f) => JSON.parse(readFileSync(join(tasksDir, f), "utf8")));
const reply = (findings: string[], rw: Rewrite) => "Done.\n\n```json\n" + JSON.stringify({ findings: findings.map((rule) => ({ rule, fix: "x" })), rewrite: rw }) + "\n```\n";
const perfectRw = (t: Task): Rewrite => ({
  description: `${t.job}`.padEnd(DESC_MIN_CHARS, "."),
  readme: `# X\n\n## Summary\n\n${t.job} ${t.must_keep.join(", ")}.\n\n## Key features\n\n- a\n\n## Usage\n\nAsk.\n\n## Use cases\n\nb\n\n## Limitations\n\nc\n\n## Metadata\n\nv1\n`.padEnd(README_MIN_CHARS + 10, " ") + "end",
  keywords: [t.must_keep[0]], starter_prompts: ["Try me"],
});
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const arg = process.argv[2];
  if (arg === "--selftest") {
    const tasks = load();
    const check = (n: string, got: number, want: number) => { const ok = got === want; console.log(`${ok ? "ok  " : "FAIL"} ${n}: ${got}${ok ? "" : ` (want ${want})`}`); if (!ok) process.exitCode = 1; };
    const perfect = tasks.map((t) => scoreTask(t, reply(t.expected.map((e) => e.rule), perfectRw(t))));
    check("perfect score", scoreRun(perfect).score, 100);
    check("perfect passes", scoreRun(perfect).tasks_passed, tasks.length);
    check("unparseable", scoreRun(tasks.map((t) => scoreTask(t, "no json"))).score, 0);
    check("empty findings + empty rewrite", scoreRun(tasks.map((t) => scoreTask(t, reply([], { description: "", readme: "", keywords: [], starter_prompts: [] })))).score, 0);
    const noisy = tasks.map((t) => scoreTask(t, reply([...t.expected.map((e) => e.rule), "website"], perfectRw(t))));
    const want = round(100 * tasks.reduce((s, t) => s + 0.5 * Math.max(0, t.expected.length - 0.5) / t.expected.length + 0.5, 0) / tasks.length, 2);
    check("all caught + one noise", scoreRun(noisy).score, want);
    const a = JSON.stringify(perfect), b = JSON.stringify(tasks.map((t) => scoreTask(t, reply(t.expected.map((e) => e.rule), perfectRw(t)))));
    check("deterministic (same input twice)", a === b ? 1 : 0, 1);
  } else if (arg) {
    const results = JSON.parse(readFileSync(join(resolve(arg), "results.json"), "utf8")) as { task_id: string; reply: string }[];
    const byId = new Map(load().map((t) => [t.id, t]));
    const s = results.map((r) => scoreTask(byId.get(r.task_id)!, r.reply));
    for (const t of s) console.log(`${t.passed ? "pass" : "    "} ${t.task_id.padEnd(22)} ${t.score.toFixed(2)} diag ${t.diagnosis} rw ${t.rewrite} missed ${t.missed.map((m) => m.rule)} noise ${t.noise}`);
    console.log(JSON.stringify(scoreRun(s)));
  } else console.log("usage: npm run score -- --selftest | <run dir>");
}
